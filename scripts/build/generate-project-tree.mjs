import { readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const excluded = new Set(['.git', '.DS_Store', 'dist', 'node_modules']);

async function entries(directory) {
  return (await readdir(directory, { withFileTypes: true }))
    .filter((entry) => !excluded.has(entry.name))
    .sort((left, right) => Number(right.isDirectory()) - Number(left.isDirectory()) || left.name.localeCompare(right.name));
}

async function render(directory, prefix = '') {
  const children = await entries(directory);
  const lines = [];
  for (const [index, entry] of children.entries()) {
    const last = index === children.length - 1;
    lines.push(`${prefix}${last ? '└──' : '├──'} ${entry.name}${entry.isDirectory() ? '/' : ''}`);
    if (entry.isDirectory()) lines.push(...await render(resolve(directory, entry.name), `${prefix}${last ? '    ' : '│   '}`));
  }
  return lines;
}

const tree = ['CnC-TA-Suite/', ...await render(repo)].join('\n');
const content = `# Project Tree\n\nGenerated by \`node scripts/build/generate-project-tree.mjs\`. Build output and local metadata are intentionally omitted.\n\n\`\`\`text\n${tree}\n\`\`\`\n`;
await writeFile(resolve(repo, 'PROJECT_TREE.md'), content);
console.log('Updated PROJECT_TREE.md');

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const modulesRoot = resolve(repo, 'modules');
const output = resolve(repo, 'core/modules/moduleCatalog.generated.js');

function toImportPath(fromFile, targetFile) {
  let path = relative(dirname(fromFile), targetFile).split(sep).join('/');
  if (!path.startsWith('.')) path = `./${path}`;
  return path;
}

async function findEntry(directory) {
  const files = await readdir(directory, { withFileTypes: true });
  const names = new Set(files.filter((entry) => entry.isFile()).map((entry) => entry.name));

  if (names.has('index.js')) return resolve(directory, 'index.js');

  const javascriptFiles = [...names]
    .filter((name) => name.endsWith('.js'))
    .filter((name) => !/Window\.js$|\.test\.js$/i.test(name))
    .sort();

  for (const name of javascriptFiles) {
    const file = resolve(directory, name);
    const source = await readFile(file, 'utf8');
    if (/export\s+(?:default\s+)?class\s+\w+Module\b/.test(source)) return file;
    if (/export\s*\{[^}]*\w+Module[^}]*\}/s.test(source)) return file;
  }

  return null;
}

async function exportedClassName(file) {
  const source = await readFile(file, 'utf8');
  const classMatch = source.match(/export\s+(?:default\s+)?class\s+(\w+Module)\b/);
  if (classMatch) return classMatch[1];

  const namedMatch = source.match(/export\s*\{[^}]*\b(\w+Module)\b[^}]*\}/s);
  if (namedMatch) return namedMatch[1];

  throw new Error(`Unable to determine module class exported by ${file}`);
}

export async function generateModuleCatalog({ repo: repoRoot = repo } = {}) {
  const modulesRoot = resolve(repoRoot, 'modules');
  const output = resolve(repoRoot, 'core/modules/moduleCatalog.generated.js');

  const directories = (await readdir(modulesRoot, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith('.'))
    .sort((left, right) => left.name.localeCompare(right.name));

  const discovered = [];

  for (const directory of directories) {
    const entry = await findEntry(resolve(modulesRoot, directory.name));
    if (!entry) continue;

    discovered.push({
      directory: directory.name,
      entry,
      className: await exportedClassName(entry)
    });
  }

  const imports = discovered.map(({ entry, className }) =>
    `import { ${className} } from '${toImportPath(output, entry)}';`
  );

  const generated = `/*
 * AUTO-GENERATED FILE — DO NOT EDIT.
 * Generated by scripts/build/generate-module-catalog.mjs
 */

${imports.join('\n')}

export const registeredModules = Object.freeze([
${discovered.map(({ className }) => `  ${className}`).join(',\n')}
]);

export default registeredModules;
`;

  await writeFile(output, generated, 'utf8');
  console.log(`Generated module catalog with ${discovered.length} module(s).`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await generateModuleCatalog();
}
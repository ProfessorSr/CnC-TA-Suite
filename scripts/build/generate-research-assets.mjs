import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const assetDirectory = resolve(repo, 'modules/research-eta/assets');
const output = resolve(repo, 'modules/research-eta/research-assets.generated.js');
const files = (await readdir(assetDirectory)).filter((name) => name.endsWith('.png')).sort();
const entries = [];
for (const file of files) {
  const key = file.slice(0, -4);
  const data = (await readFile(resolve(assetDirectory, file))).toString('base64');
  entries.push(`  ${JSON.stringify(key)}: ${JSON.stringify(`data:image/png;base64,${data}`)}`);
}
await writeFile(output, `// Generated by scripts/build/generate-research-assets.mjs.\nexport const RESEARCH_ASSETS = Object.freeze({\n${entries.join(',\n')}\n});\n`);
